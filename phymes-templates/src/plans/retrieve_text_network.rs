/// A session for retrieving text via vector search
///
/// # Notes
pub struct RetrieveTextNetwork<'a> {
    /// Session
    pub network_name: &'a str,
}

impl<'a> Default for RetrieveTextNetwork<'a> {
    fn default() -> Self {
        Self {
            network_name: "retrieve_text_network",
        }
    }
}

